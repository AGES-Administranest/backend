import { Injectable } from '@nestjs/common';
import { Prisma, Report, ReportKind, ReportStatus } from '@prisma/client';

import { runQuery } from '../../infra/prisma/prisma-errors';
import { PrismaService } from '../../infra/prisma/prisma.service';

export interface ReportHistoryPage {
  kind?: ReportKind;
  page: number;
  limit: number;
}

/** What the history shows: stored and not deleted, owned by the user. */
const listed = (userId: string): Prisma.ReportWhereInput => ({
  userId,
  status: ReportStatus.DONE,
  deletedAt: null,
});

export interface PendingReport {
  id: string;
  userId: string;
  kind: ReportKind;
  periodStart: Date;
  periodEnd: Date;
  filters: Prisma.InputJsonValue;
  /** The key of the file in the bucket, not a URL: a signed URL expires. */
  fileKey: string;
  fileName: string;
  fileBytesSize: number;
}

/**
 * The `report` table (US32). Every query carries the user (ADR-11), the status
 * changes included, even though their id was generated by the API itself.
 */
@Injectable()
export class ReportHistoryRepository {
  constructor(private readonly prisma: PrismaService) {}

  async createPending(report: PendingReport): Promise<void> {
    await runQuery(() =>
      this.prisma.report.create({
        data: {
          id: report.id,
          userId: report.userId,
          kind: report.kind,
          periodStart: report.periodStart,
          periodEnd: report.periodEnd,
          filters: report.filters,
          fileUrl: report.fileKey,
          fileName: report.fileName,
          fileBytesSize: report.fileBytesSize,
          status: ReportStatus.PENDING,
        },
      }),
    );
  }

  /** Newest first; `id` breaks a tie so a page never repeats or skips a row. */
  findPage(userId: string, query: ReportHistoryPage): Promise<Report[]> {
    return runQuery(() =>
      this.prisma.report.findMany({
        where: {
          ...listed(userId),
          ...(query.kind ? { kind: query.kind } : {}),
        },
        orderBy: [{ createdAt: 'desc' }, { id: 'desc' }],
        skip: (query.page - 1) * query.limit,
        take: query.limit,
      }),
    );
  }

  /** The report only if the history would list it. */
  findListed(id: string, userId: string): Promise<Report | null> {
    return runQuery(() =>
      this.prisma.report.findFirst({ where: { id, ...listed(userId) } }),
    );
  }

  /**
   * Removes the report from the history; the row and its key stay. The
   * condition is in the write, so of two concurrent deletes only one wins.
   *
   * @returns The deleted row, whose `file_url` locates the file; null when the
   * history did not list it.
   */
  async softDelete(id: string, userId: string): Promise<Report | null> {
    const [deleted] = await runQuery(() =>
      this.prisma.report.updateManyAndReturn({
        where: { id, ...listed(userId) },
        data: { deletedAt: new Date() },
      }),
    );
    return deleted ?? null;
  }

  /** False when the row is no longer `PENDING`: a report is finished once. */
  markDone(id: string, userId: string): Promise<boolean> {
    return this.finish(id, userId, ReportStatus.DONE);
  }

  /** False when the row is no longer `PENDING`: a report is finished once. */
  markFailed(id: string, userId: string): Promise<boolean> {
    return this.finish(id, userId, ReportStatus.FAILED);
  }

  private async finish(
    id: string,
    userId: string,
    status: ReportStatus,
  ): Promise<boolean> {
    const { count } = await runQuery(() =>
      this.prisma.report.updateMany({
        where: { id, userId, status: ReportStatus.PENDING },
        data: { status },
      }),
    );
    return count === 1;
  }
}
